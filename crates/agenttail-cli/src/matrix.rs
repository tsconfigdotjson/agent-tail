//! `agenttail support-matrix`: generate `docs/support-matrix.md` from the discovery specs,
//! fixture metadata and the CI scenario lists.
//!
//! The classification is deliberately evidence-first:
//! - `CI-verified`: at least one scenario is listed for the harness in `harness-ci/ci`.
//! - `donated-verified`: no CI run, but a real donated fixture exists.
//! - `ported-unverified`: only hand-made/synthetic fixtures, or an adapter with no artifact.
//! - `unsupported`: no adapter/discovery spec at all.

use agenttail::Harness;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

struct Fixture {
    harness: String,
    version: String,
    os: String,
    capture: String,
    scenario: String,
}

pub fn run(args: &[String]) -> Result<ExitCode, String> {
    let mut root = None;
    let mut out = None;
    let mut check = false;
    let mut iter = args.iter();
    while let Some(arg) = iter.next() {
        match arg.as_str() {
            "--root" => root = Some(PathBuf::from(iter.next().ok_or("--root needs a value")?)),
            "--out" => out = Some(PathBuf::from(iter.next().ok_or("--out needs a value")?)),
            "--check" => check = true,
            other => return Err(format!("no option \"{other}\"")),
        }
    }
    let root = match root {
        Some(root) => root,
        None => find_root().ok_or("support-matrix: run from the repository or pass --root")?,
    };
    let text = generate(&root)?;
    let out = out.unwrap_or_else(|| root.join("docs/support-matrix.md"));
    if check {
        let current = std::fs::read_to_string(&out).unwrap_or_default();
        if current != text {
            eprintln!("support-matrix: {} is out of date; run `agenttail support-matrix`", out.display());
            return Ok(ExitCode::FAILURE);
        }
        println!("support-matrix: {} is up to date", out.display());
        return Ok(ExitCode::SUCCESS);
    }
    if let Some(parent) = out.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    std::fs::write(&out, text).map_err(|e| format!("{}: {e}", out.display()))?;
    println!("support-matrix: wrote {}", out.display());
    Ok(ExitCode::SUCCESS)
}

fn find_root() -> Option<PathBuf> {
    let mut dir = std::env::current_dir().ok()?;
    loop {
        if dir.join("spec/discovery").is_dir() && dir.join("harness-ci").is_dir() {
            return Some(dir);
        }
        if !dir.pop() {
            return None;
        }
    }
}

fn generate(root: &Path) -> Result<String, String> {
    let fixtures = fixtures(root)?;
    let ci = ci_scenarios(root)?;
    let mut lines = vec![
        "# Support matrix".to_string(),
        String::new(),
        "<!-- @generated by `agenttail support-matrix`; do not edit by hand. -->".to_string(),
        String::new(),
        "Evidence levels, strongest first: **CI-verified** (a scenario runs in the harness CI".to_string(),
        "matrix), **donated-verified** (a real session captured offline and redacted),".to_string(),
        "**ported-unverified** (only a hand-made/synthetic artifact, or an adapter with no".to_string(),
        "artifact yet), **spike** (a docs-only investigation; no adapter, fixture or CI run), and".to_string(),
        "**unsupported** (no discovery spec or adapter).".to_string(),
        String::new(),
        "| Harness | Status | CI scenarios | Fixtures | Versions | Evidence |".to_string(),
        "|---|---|---:|---:|---|---|".to_string(),
    ];
    for harness in Harness::ALL {
        let id = harness.id();
        let fixt: Vec<&Fixture> = fixtures.iter().filter(|fixture| fixture.harness == id).collect();
        let ci: Vec<&str> = ci.get(id).map(|names| names.iter().map(String::as_str).collect()).unwrap_or_default();
        let donated = fixt.iter().filter(|fixture| fixture.capture == "donated").count();
        let ci_scripted = fixt.iter().filter(|fixture| fixture.capture == "ci-scripted").count();
        let handmade = fixt.iter().filter(|fixture| fixture.capture == "handmade").count();
        let status = if !ci.is_empty() || ci_scripted > 0 {
            "CI-verified"
        } else if donated > 0 {
            "donated-verified"
        } else if !fixt.is_empty() {
            "ported-unverified"
        } else {
            "unsupported"
        };
        let versions = versions(&fixt);
        let evidence = if !ci.is_empty() || ci_scripted > 0 {
            format!(
                "{} CI scenario(s); {ci_scripted} ci-scripted, {donated} donated, {handmade} hand-made fixture(s)",
                ci.len()
            )
        } else if donated > 0 {
            format!("{donated} donated fixture(s); no CI scenario")
        } else if handmade > 0 {
            format!("{handmade} hand-made/synthetic fixture(s); no real capture")
        } else {
            "adapter present, no artifact".to_string()
        };
        lines.push(format!(
            "| {} | **{status}** | {} | {} | {} | {} |",
            harness.name(),
            ci.len(),
            fixt.len(),
            versions,
            evidence
        ));
    }
    lines.push(String::new());
    lines.push("## Spike-only (not supported)".to_string());
    lines.push(String::new());
    lines.push("| Target | Status | CI scenarios | Fixtures | Versions | Evidence |".to_string());
    lines.push("|---|---|---:|---:|---|---|".to_string());
    lines.push(
        "| Claude Desktop (agent mode) | **spike** | 0 | 0 | unknown | docs-only Jev computer-use loop; no adapter, fixture or CI run |"
            .to_string(),
    );
    lines.push(String::new());
    lines.push(
        "Claude Desktop is a spike-only target, not a supported harness: it has no discovery spec or adapter and is not in the table above. See [docs/formats/claude-desktop.md](formats/claude-desktop.md)."
            .to_string(),
    );
    lines.push(String::new());
    lines.push("## What each harness can read".to_string());
    lines.push(String::new());
    lines.push("| Harness | Root (below home) | Ask-user tools | Modes observed | Helpers | Quirks |".to_string());
    lines.push("|---|---|---|---|---|---|".to_string());
    for harness in Harness::ALL {
        let discovery = harness.discovery();
        let asks: Vec<_> = discovery.asks_user.iter().map(|name| format!("`{name}`")).collect();
        let modes: Vec<_> =
            discovery.modes.iter().filter(|mode| mode.observed).map(|mode| format!("`{}`", mode.value)).collect();
        let helpers = if discovery.layout.helpers_in.is_some() { "yes" } else { "no" };
        lines.push(format!(
            "| {} | `{}` | {} | {} | {} | {} |",
            harness.name(),
            discovery.roots.default,
            if asks.is_empty() { "none observed".to_string() } else { asks.join(", ") },
            if modes.is_empty() { "none observed".to_string() } else { modes.join(", ") },
            helpers,
            discovery.quirks.len()
        ));
    }
    lines.push(String::new());
    lines.push("## Fixture detail".to_string());
    lines.push(String::new());
    lines.push("| Harness | Version | OS | Capture | Scenario |".to_string());
    lines.push("|---|---|---|---|---|".to_string());
    let mut fixtures = fixtures;
    fixtures.sort_by(|a, b| {
        (&a.harness, &a.version, &a.os, &a.scenario).cmp(&(&b.harness, &b.version, &b.os, &b.scenario))
    });
    for fixture in fixtures {
        lines.push(format!(
            "| {} | `{}` | `{}` | `{}` | `{}` |",
            fixture.harness, fixture.version, fixture.os, fixture.capture, fixture.scenario
        ));
    }
    lines.push(String::new());
    lines.push("Harnesses with no discovery spec are unsupported by definition; this generated".to_string());
    lines.push("table lists every harness that does have one. Spike-only targets are listed".to_string());
    lines.push("separately above and are not adapters. `agenttail survey --drift` checks".to_string());
    lines.push("the transcript shape against `spec/baseline/`.".to_string());
    lines.push(String::new());
    Ok(lines.join("\n"))
}

fn versions(fixtures: &[&Fixture]) -> String {
    let versions: BTreeSet<_> =
        fixtures.iter().map(|fixture| fixture.version.as_str()).filter(|v| *v != "unknown").collect();
    if versions.is_empty() {
        "unknown".to_string()
    } else {
        versions.into_iter().map(|version| format!("`{version}`")).collect::<Vec<_>>().join(", ")
    }
}

fn fixtures(root: &Path) -> Result<Vec<Fixture>, String> {
    let mut files = Vec::new();
    collect_meta(&root.join("fixtures"), &mut files)?;
    files.sort();
    let mut fixtures = Vec::new();
    for path in files {
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let scenario = path
            .parent()
            .and_then(|dir| dir.strip_prefix(root.join("fixtures")).ok())
            .map(|rel| rel.to_string_lossy().replace('\\', "/"))
            .unwrap_or_default();
        fixtures.push(Fixture {
            harness: meta_value(&text, "harness").unwrap_or_default(),
            version: meta_value(&text, "version").unwrap_or_default(),
            os: meta_value(&text, "os").unwrap_or_default(),
            capture: meta_value(&text, "capture").unwrap_or_default(),
            scenario,
        });
    }
    Ok(fixtures)
}

fn collect_meta(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(format!("{}: {error}", dir.display())),
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_meta(&path, out)?;
        } else if path.file_name().is_some_and(|name| name == "meta.toml") {
            out.push(path);
        }
    }
    Ok(())
}

fn meta_value(text: &str, key: &str) -> Option<String> {
    for line in text.lines() {
        let line = line.trim();
        let Some((name, value)) = line.split_once('=') else { continue };
        if name.trim() != key {
            continue;
        }
        let value = value.trim();
        let value = value.strip_prefix('"').and_then(|value| value.strip_suffix('"')).unwrap_or(value);
        return Some(value.replace("\\\"", "\"").replace("\\\\", "\\"));
    }
    None
}

fn ci_scenarios(root: &Path) -> Result<BTreeMap<String, BTreeSet<String>>, String> {
    let mut scenarios = BTreeMap::new();
    for name in [
        "scenarios.txt",
        "scenarios-codex.txt",
        "scenarios-pi.txt",
        "scenarios-opencode.txt",
        "scenarios-gemini.txt",
        "scenarios-copilot.txt",
    ] {
        let path = root.join("harness-ci/ci").join(name);
        let Ok(text) = std::fs::read_to_string(&path) else { continue };
        for line in text.lines() {
            let scenario = line.trim();
            if scenario.is_empty() || scenario.starts_with('#') {
                continue;
            }
            let driver = root.join("harness-ci/driver/scenarios").join(format!("{scenario}.json"));
            let harness = std::fs::read_to_string(&driver)
                .ok()
                .and_then(|text| serde_json::from_str::<Value>(&text).ok())
                .and_then(|value| value.get("harness").and_then(Value::as_str).map(str::to_string))
                .unwrap_or_else(|| {
                    if name.contains("codex") {
                        "codex".into()
                    } else if name.contains("pi") {
                        "pi".into()
                    } else if name.contains("opencode") {
                        "opencode".into()
                    } else if name.contains("gemini") {
                        "gemini".into()
                    } else if name.contains("copilot") {
                        "copilot".into()
                    } else {
                        "claude_code".into()
                    }
                });
            scenarios.entry(harness).or_insert_with(BTreeSet::new).insert(scenario.to_string());
        }
    }
    Ok(scenarios)
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    #[test]
    fn meta_values_are_quoted_strings() {
        let text = "harness = \"claude_code\"\ncapture = \"donated\"\n";
        assert_eq!(meta_value(text, "harness").as_deref(), Some("claude_code"));
        assert_eq!(meta_value(text, "capture").as_deref(), Some("donated"));
        assert_eq!(meta_value(text, "missing"), None);
    }

    #[test]
    fn classification_prefers_ci_then_donated_then_handmade() {
        let temp = TempDir::new().unwrap();
        let root = temp.path();
        for (harness, capture) in [("claude_code", "donated"), ("codex", "handmade"), ("pi", "ci-scripted")] {
            let dir = root.join(format!("fixtures/{harness}/1/linux/s"));
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(
                dir.join("meta.toml"),
                format!("harness = \"{harness}\"\nversion = \"1\"\nos = \"linux\"\ncapture = \"{capture}\"\n"),
            )
            .unwrap();
        }
        let claude = root.join("harness-ci/ci/scenarios.txt");
        std::fs::create_dir_all(claude.parent().unwrap()).unwrap();
        std::fs::write(&claude, "claude_plain_qa\n").unwrap();
        let driver = root.join("harness-ci/driver/scenarios/claude_plain_qa.json");
        std::fs::create_dir_all(driver.parent().unwrap()).unwrap();
        std::fs::write(&driver, r#"{"harness":"claude_code"}"#).unwrap();
        let text = generate(root).unwrap();
        assert!(text.contains("| Claude Code | **CI-verified** |"), "{text}");
        assert!(text.contains("| Codex | **ported-unverified** |"), "{text}");
        assert!(text.contains("| Pi | **CI-verified** |"), "{text}");
        assert!(text.contains("| Cursor | **unsupported** |"), "{text}");
        assert!(text.contains("| Claude Desktop (agent mode) | **spike** |"), "{text}");
    }
}
