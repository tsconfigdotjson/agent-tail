//! Embed `spec/discovery/*.toml` in the crate.
//!
//! The discovery files are the source of every harness's `Layout`, root overrides, ask-user
//! names, never-prompt observations, mode vocabulary, timestamp rules, and quirks. Generating
//! Rust at build time (rather than parsing TOML at runtime) keeps those facts read-only,
//! dependency-free at runtime, and checked before the crate compiles.

use serde::Deserialize;
use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Spec {
    schema: u32,
    harness: String,
    name: String,
    roots: Roots,
    layout: LayoutSpec,
    project: Project,
    timestamps: Timestamps,
    asks_user: AsksUser,
    never_prompt: NeverPrompt,
    modes: Modes,
    #[serde(default)]
    quirks: Vec<Quirk>,
    registry: Option<Registry>,
    database: Option<Database>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Roots {
    default: String,
    evidence: String,
    #[serde(default)]
    env: Vec<EnvRoot>,
    #[serde(default)]
    platform: Vec<PlatformRoot>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PlatformRoot {
    os: String,
    path: String,
    build: String,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct EnvRoot {
    var: String,
    append: String,
    absolute: bool,
    semantics: String,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct LayoutSpec {
    max_depth: Option<usize>,
    session_pattern: String,
    sessions_in: Option<String>,
    session_dir_prefix: Option<String>,
    #[serde(default)]
    session_dir_hex8: bool,
    helpers_in: Option<String>,
    helper_owner: Option<String>,
    day_folders: bool,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Project {
    source: String,
    encoding: String,
    evidence: String,
    #[serde(default)]
    examples: Vec<ProjectExample>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct ProjectExample {
    cwd: String,
    folder: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Timestamps {
    field: String,
    format: String,
    timezone: String,
    fallback: String,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct AsksUser {
    #[serde(rename = "match")]
    matching: String,
    evidence: String,
    #[serde(default)]
    values: Vec<AskTool>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct AskTool {
    name: String,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct NeverPrompt {
    evidence: String,
    #[serde(default)]
    values: Vec<NeverPromptTool>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct NeverPromptTool {
    tool: String,
    modes: Vec<String>,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Modes {
    evidence: String,
    #[serde(default)]
    values: Vec<Mode>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Mode {
    value: String,
    can_ask_human: bool,
    observed: bool,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Quirk {
    id: String,
    summary: String,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Database {
    file: String,
    channel_pattern: String,
    env: Option<String>,
    evidence: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Registry {
    path: String,
    used: bool,
    statuses: Vec<String>,
    waiting_for: Vec<String>,
    removed_on_graceful_exit: bool,
    removed_on_sigkill: bool,
    reason: String,
    evidence: Vec<String>,
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let spec_dir = manifest.join("../../spec/discovery");
    let files = [
        ("claude-code.toml", "ClaudeCode", "claude_code"),
        ("claude-desktop.toml", "ClaudeDesktop", "claude_desktop"),
        ("codex.toml", "Codex", "codex"),
        ("cursor.toml", "Cursor", "cursor"),
        ("pi.toml", "Pi", "pi"),
        ("opencode.toml", "OpenCode", "opencode"),
        ("gemini.toml", "Gemini", "gemini"),
        ("copilot.toml", "Copilot", "copilot"),
    ];

    let mut generated = String::from(
        "// @generated by crates/agenttail/build.rs from spec/discovery/*.toml. Do not edit.\n\
         pub(crate) static ALL_DISCOVERY: &[Discovery] = &[\n",
    );
    for (file, variant, id) in files {
        let path = spec_dir.join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        let text = fs::read_to_string(&path).unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
        let spec: Spec = toml::from_str(&text).unwrap_or_else(|error| panic!("parse {}: {error}", path.display()));
        validate(&spec, id).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        render(&mut generated, &spec, variant);
    }
    generated.push_str("];\n");

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("discovery_generated.rs");
    fs::write(&out, generated).unwrap_or_else(|error| panic!("write {}: {error}", out.display()));
}

fn validate(spec: &Spec, expected_id: &str) -> Result<(), String> {
    require(spec.schema == 1, "schema must be 1")?;
    require(spec.harness == expected_id, format!("harness must be {expected_id:?}"))?;
    require(!spec.name.trim().is_empty(), "name is empty")?;

    let roots = &spec.roots;
    relative(&roots.default, "roots.default")?;
    require(!roots.evidence.trim().is_empty(), "roots.evidence is empty")?;
    let mut platform = std::collections::HashSet::new();
    for root in &roots.platform {
        require(
            matches!(root.os.as_str(), "linux" | "macos" | "windows"),
            format!("roots.platform os {:?} is not linux, macos or windows", root.os),
        )?;
        require(!root.build.trim().is_empty(), "a roots.platform build is empty")?;
        require(
            matches!(root.build.as_str(), "consumer" | "third_party"),
            format!("roots.platform build {:?} is not consumer or third_party", root.build),
        )?;
        relative(&root.path, &format!("roots.platform[{0}]", root.os))?;
        require(!root.evidence.trim().is_empty(), "a roots.platform entry has no evidence")?;
        require(
            platform.insert((root.os.clone(), root.build.clone())),
            format!("roots.platform repeats {} {}", root.os, root.build),
        )?;
    }
    let mut env_vars = std::collections::HashSet::new();
    for env in &roots.env {
        require(!env.var.trim().is_empty(), "a roots.env var is empty")?;
        require(env_vars.insert(&env.var), format!("roots.env repeats {}", env.var))?;
        // An empty append replaces the root with the variable's value (Pi's session dir).
        if !env.append.is_empty() {
            relative(&env.append, &format!("roots.env[{0}].append", env.var))?;
        }
        require(!env.semantics.trim().is_empty(), format!("roots.env[{0}] has no semantics", env.var))?;
        require(!env.evidence.trim().is_empty(), format!("roots.env[{0}] has no evidence", env.var))?;
    }

    let layout = &spec.layout;
    require(!layout.evidence.trim().is_empty(), "layout.evidence is empty")?;
    require(
        layout.helpers_in.is_none() || layout.max_depth.is_some(),
        "helpers_in needs max_depth (Layout::role can't find helpers without one)",
    )?;
    require(
        layout.helpers_in.is_some() == layout.helper_owner.is_some(),
        "helpers_in and helper_owner must be given together",
    )?;
    if let Some(owner) = &layout.helper_owner {
        require(
            matches!(owner.as_str(), "session_file_stem" | "session_folder"),
            format!("helper_owner {owner:?} is not session_file_stem or session_folder"),
        )?;
    }
    session_pattern(&layout.session_pattern)?;
    if let Some(name) = &layout.sessions_in {
        require(!name.trim().is_empty(), "layout.sessions_in is empty")?;
    }
    if let Some(prefix) = &layout.session_dir_prefix {
        require(!prefix.trim().is_empty(), "layout.session_dir_prefix is empty")?;
        require(!prefix.contains(['/', '\\']), "layout.session_dir_prefix is a folder-name prefix")?;
    }
    if let Some(name) = &layout.helpers_in {
        require(!name.trim().is_empty(), "layout.helpers_in is empty")?;
    }

    require(!spec.project.source.trim().is_empty(), "project.source is empty")?;
    require(!spec.project.encoding.trim().is_empty(), "project.encoding is empty")?;
    require(!spec.project.evidence.trim().is_empty(), "project.evidence is empty")?;
    for example in &spec.project.examples {
        require(!example.cwd.trim().is_empty(), "a project example has no cwd")?;
        require(!example.folder.trim().is_empty(), "a project example has no folder")?;
    }

    require(!spec.timestamps.field.trim().is_empty(), "timestamps.field is empty")?;
    require(!spec.timestamps.format.trim().is_empty(), "timestamps.format is empty")?;
    require(!spec.timestamps.timezone.trim().is_empty(), "timestamps.timezone is empty")?;
    require(!spec.timestamps.fallback.trim().is_empty(), "timestamps.fallback is empty")?;
    require(!spec.timestamps.evidence.trim().is_empty(), "timestamps.evidence is empty")?;

    require(
        matches!(spec.asks_user.matching.as_str(), "exact" | "alnum_lower"),
        "asks_user.match must be exact or alnum_lower",
    )?;
    require(!spec.asks_user.evidence.trim().is_empty(), "asks_user.evidence is empty")?;
    let mut ask_names = std::collections::HashSet::new();
    for tool in &spec.asks_user.values {
        require(!tool.name.trim().is_empty(), "an asks_user name is empty")?;
        require(ask_names.insert(&tool.name), format!("asks_user repeats {}", tool.name))?;
        require(!tool.evidence.trim().is_empty(), format!("asks_user {} has no evidence", tool.name))?;
    }

    require(!spec.never_prompt.evidence.trim().is_empty(), "never_prompt.evidence is empty")?;
    let mut never_seen = std::collections::HashSet::new();
    for tool in &spec.never_prompt.values {
        require(!tool.tool.trim().is_empty(), "a never_prompt tool is empty")?;
        require(!tool.modes.is_empty(), format!("never_prompt {} names no mode", tool.tool))?;
        for mode in &tool.modes {
            require(!mode.trim().is_empty(), format!("never_prompt {} names an empty mode", tool.tool))?;
            require(
                spec.modes.values.iter().any(|known| &known.value == mode),
                format!("never_prompt {} names {mode:?}, which is not in this harness's modes", tool.tool),
            )?;
            require(never_seen.insert((&tool.tool, mode)), format!("never_prompt repeats {} under {mode}", tool.tool))?;
        }
        require(!tool.evidence.trim().is_empty(), format!("never_prompt {} has no evidence", tool.tool))?;
    }

    require(!spec.modes.evidence.trim().is_empty(), "modes.evidence is empty")?;
    let mut mode_values = std::collections::HashSet::new();
    for mode in &spec.modes.values {
        require(!mode.value.trim().is_empty(), "a mode value is empty")?;
        require(mode_values.insert(&mode.value), format!("modes repeats {}", mode.value))?;
        require(!mode.evidence.trim().is_empty(), format!("mode {} has no evidence", mode.value))?;
    }

    require(!spec.quirks.is_empty(), "quirks is empty")?;
    let mut ids = std::collections::HashSet::new();
    for quirk in &spec.quirks {
        require(!quirk.id.trim().is_empty(), "a quirk id is empty")?;
        require(ids.insert(&quirk.id), format!("quirks repeats {}", quirk.id))?;
        require(!quirk.summary.trim().is_empty(), format!("quirk {} has no summary", quirk.id))?;
        require(!quirk.evidence.trim().is_empty(), format!("quirk {} has no evidence", quirk.id))?;
    }

    if let Some(database) = &spec.database {
        require(!database.file.trim().is_empty(), "database.file is empty")?;
        require(!database.file.contains(['/', '\\']), "database.file must be a file name")?;
        require(!database.channel_pattern.trim().is_empty(), "database.channel_pattern is empty")?;
        require(
            database.channel_pattern.contains('*') && !database.channel_pattern.contains(['/', '\\']),
            "database.channel_pattern must be a file pattern",
        )?;
        if let Some(var) = &database.env {
            require(!var.trim().is_empty(), "database.env is empty")?;
        }
        require(!database.evidence.trim().is_empty(), "database.evidence is empty")?;
    }

    if let Some(registry) = &spec.registry {
        require(!registry.path.trim().is_empty(), "registry.path is empty")?;
        require(!registry.reason.trim().is_empty(), "registry.reason is empty")?;
        require(!registry.evidence.is_empty(), "registry.evidence is empty")?;
        for item in registry.evidence.iter().chain(&registry.statuses).chain(&registry.waiting_for) {
            require(!item.trim().is_empty(), "registry has an empty status, waiting_for, or evidence item")?;
        }
    }
    Ok(())
}

fn relative(path: &str, field: &str) -> Result<(), String> {
    require(!path.trim().is_empty(), format!("{field} is empty"))?;
    require(!path.starts_with('/') && !path.starts_with('~'), format!("{field} must be relative to home"))?;
    require(!path.contains('\\'), format!("{field} must use '/' separators"))?;
    Ok(())
}

/// A session pattern: `*.jsonl` (any file with that extension) or a bare file name such as
/// `audit.jsonl` (only that file). Returns the extension the walker filters on and, for a
/// bare name, the exact file name the layout also requires.
fn session_pattern(pattern: &str) -> Result<(&str, Option<&str>), String> {
    if let Some(suffix) = pattern
        .strip_prefix("*.")
        .filter(|suffix| !suffix.is_empty() && !suffix.contains(['/', '\\']) && !suffix.contains('*'))
    {
        return Ok((suffix, None));
    }
    let (_, suffix) = pattern
        .split_once('.')
        .filter(|(name, suffix)| {
            !name.is_empty() && !suffix.is_empty() && !pattern.contains(['/', '\\']) && !pattern.contains('*')
        })
        .ok_or_else(|| format!("session_pattern {pattern:?} is not '*.extension' or a bare file name"))?;
    Ok((suffix, Some(pattern)))
}

fn require(condition: bool, message: impl Into<String>) -> Result<(), String> {
    if condition { Ok(()) } else { Err(message.into()) }
}

fn render(out: &mut String, spec: &Spec, variant: &str) {
    let layout = &spec.layout;
    let (suffix, session_file) = session_pattern(&layout.session_pattern).expect("validated");
    let session_file = opt_string(session_file);
    let max_depth = opt_usize(layout.max_depth);
    let sessions_in = opt_string(layout.sessions_in.as_deref());
    let session_dir_prefix = opt_string(layout.session_dir_prefix.as_deref());
    let session_dir_hex8 = layout.session_dir_hex8;
    let helpers_in = opt_string(layout.helpers_in.as_deref());
    let helper_owner = layout
        .helper_owner
        .as_deref()
        .map(|owner| match owner {
            "session_file_stem" => "HelperOwner::SessionFileStem",
            "session_folder" => "HelperOwner::SessionFolder",
            _ => unreachable!("validated"),
        })
        .unwrap_or("HelperOwner::SessionFolder");
    let ask_match = match spec.asks_user.matching.as_str() {
        "exact" => "AskMatch::Exact",
        "alnum_lower" => "AskMatch::AlnumLower",
        _ => unreachable!("validated"),
    };

    writeln!(out, "    Discovery {{").unwrap();
    writeln!(out, "        harness: Harness::{variant},").unwrap();
    writeln!(
        out,
        "        roots: Roots {{ default: {}, env: &[{}], platform: &[{}], evidence: {} }},",
        lit(&spec.roots.default),
        spec.roots
            .env
            .iter()
            .map(|env| format!(
                "EnvRoot {{ var: {}, append: {}, absolute: {}, semantics: {}, evidence: {} }}",
                lit(&env.var),
                lit(&env.append),
                env.absolute,
                lit(&env.semantics),
                lit(&env.evidence)
            ))
            .collect::<Vec<_>>()
            .join(", "),
        spec.roots
            .platform
            .iter()
            .map(|root| format!(
                "PlatformRoot {{ os: {}, path: {}, build: {}, evidence: {} }}",
                lit(&root.os),
                lit(&root.path),
                lit(&root.build),
                lit(&root.evidence)
            ))
            .collect::<Vec<_>>()
            .join(", "),
        lit(&spec.roots.evidence)
    )
    .unwrap();
    writeln!(
        out,
        "        layout: Layout {{ root: {}, max_depth: {max_depth}, sessions_in: {sessions_in}, session_dir_prefix: {session_dir_prefix}, session_dir_hex8: {session_dir_hex8}, helpers_in: {helpers_in}, helper_owner: {helper_owner}, day_folders: {}, session_suffix: {}, session_file: {session_file} }},",
        lit(&spec.roots.default),
        layout.day_folders,
        lit(suffix)
    )
    .unwrap();
    writeln!(
        out,
        "        asks_user: &[{}],",
        spec.asks_user.values.iter().map(|tool| lit(&tool.name)).collect::<Vec<_>>().join(", ")
    )
    .unwrap();
    writeln!(out, "        asks_user_match: {ask_match},").unwrap();
    writeln!(
        out,
        "        never_prompt: &[{}],",
        spec.never_prompt
            .values
            .iter()
            .map(|tool| format!(
                "NeverPrompt {{ tool: {}, modes: &[{}], evidence: {} }}",
                lit(&tool.tool),
                tool.modes.iter().map(|mode| lit(mode)).collect::<Vec<_>>().join(", "),
                lit(&tool.evidence)
            ))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "        modes: &[{}],",
        spec.modes
            .values
            .iter()
            .map(|mode| format!(
                "ModeRule {{ value: {}, can_ask_human: {}, observed: {}, evidence: {} }}",
                lit(&mode.value),
                mode.can_ask_human,
                mode.observed,
                lit(&mode.evidence)
            ))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "        timestamps: TimestampRule {{ field: {}, format: {}, timezone: {}, fallback: {}, evidence: {} }},",
        lit(&spec.timestamps.field),
        lit(&spec.timestamps.format),
        lit(&spec.timestamps.timezone),
        lit(&spec.timestamps.fallback),
        lit(&spec.timestamps.evidence)
    )
    .unwrap();
    writeln!(
        out,
        "        project: ProjectRule {{ source: {}, encoding: {}, examples: &[{}], evidence: {} }},",
        lit(&spec.project.source),
        lit(&spec.project.encoding),
        spec.project
            .examples
            .iter()
            .map(|example| format!("ProjectExample {{ cwd: {}, folder: {} }}", lit(&example.cwd), lit(&example.folder)))
            .collect::<Vec<_>>()
            .join(", "),
        lit(&spec.project.evidence)
    )
    .unwrap();
    writeln!(
        out,
        "        quirks: &[{}],",
        spec.quirks
            .iter()
            .map(|quirk| format!(
                "Quirk {{ id: {}, summary: {}, evidence: {} }}",
                lit(&quirk.id),
                lit(&quirk.summary),
                lit(&quirk.evidence)
            ))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .unwrap();
    let database = spec.database.as_ref().map_or_else(
        || "None".to_string(),
        |database| {
            format!(
                "Some(Database {{ file: {}, channel_pattern: {}, env: {}, evidence: {} }})",
                lit(&database.file),
                lit(&database.channel_pattern),
                opt_string(database.env.as_deref()),
                lit(&database.evidence)
            )
        },
    );
    writeln!(out, "        database: {database},").unwrap();
    let registry = spec.registry.as_ref().map_or_else(
        || "None".to_string(),
        |registry| {
            format!(
                "Some(Registry {{ path: {}, used: {}, statuses: &[{}], waiting_for: &[{}], removed_on_graceful_exit: {}, removed_on_sigkill: {}, reason: {}, evidence: &[{}] }})",
                lit(&registry.path),
                registry.used,
                string_list(&registry.statuses),
                string_list(&registry.waiting_for),
                registry.removed_on_graceful_exit,
                registry.removed_on_sigkill,
                lit(&registry.reason),
                string_list(&registry.evidence)
            )
        },
    );
    writeln!(out, "        registry: {registry},").unwrap();
    writeln!(out, "    }},").unwrap();
}

fn lit(value: &str) -> String {
    format!("{value:?}")
}

fn opt_string(value: Option<&str>) -> String {
    value.map_or_else(|| "None".into(), |value| format!("Some({})", lit(value)))
}

fn opt_usize(value: Option<usize>) -> String {
    value.map_or_else(|| "None".into(), |value| format!("Some({value})"))
}

fn string_list(items: &[String]) -> String {
    items.iter().map(|item| lit(item)).collect::<Vec<_>>().join(", ")
}
